<!-- What the planner is for, where its data lives and what Export means. -->
<section
	class="flex flex-col gap-3 rounded-xl border border-gray-800 bg-gray-900 p-4 text-sm text-gray-300"
	aria-label="About the team planner"
>
	<p>
		Keep your teams from a Pokepaste and record each match: your picks and lead, the opposing team,
		the result and notes. The planner turns that into stats: your win rate overall, by Pokémon and
		by lead, and the opponents and leads that give you the most trouble. Any team or match can also
		be opened in the calculator.
	</p>
	<p>
		<strong class="font-semibold text-gray-100">Your data stays in this browser.</strong> Teams and matches
		are saved only on this device, in this browser: nothing is uploaded, so they don't show up on other
		devices or browsers, and clearing the site data deletes them.
	</p>
	<p>
		<strong class="font-semibold text-gray-100">What Export is for.</strong> On a team's page,
		<em>Export history</em> (or <em>Export</em> on a single match) gives you a text with your
		matches. Send it to a friend: they open one of their own teams and use <em>Import history</em>
		(or
		<em>Import match</em>) to add your matches to their stats. It also works as a backup, or to move
		your matches to another browser.
	</p>
</section>
